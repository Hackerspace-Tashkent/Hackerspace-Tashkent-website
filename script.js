var currentLang = 'en';

function setLang(lang) {
  currentLang = lang;
  var t = translations[lang];
  if (!t) return;

  document.title = t.page_title;

  // Атрибут lang не обновлялся: скринридеры и автоперевод браузера
  // всегда считали страницу английской.
  var code = lang === 'uz-lat' ? 'uz-Latn'
          : lang === 'uz-cyr' ? 'uz-Cyrl' : lang;
  document.documentElement.setAttribute('lang', code);

  var desc = t.hero_sub;
  var d = document.getElementById('page-desc');
  if (d && desc) d.setAttribute('content', desc);
  var og = document.getElementById('og-title');
  if (og) og.setAttribute('content', t.page_title + ' — ' + t.tagline);
  var tagline = document.getElementById('tagline');
  if (tagline) tagline.textContent = t.tagline;

  document.querySelectorAll('[data-key]').forEach(function (el) {
    var key = el.getAttribute('data-key');
    if (t[key]) {
      el.textContent = t[key];
    }
  });

  document.querySelectorAll('.lang-switcher a').forEach(function (a) {
    a.classList.remove('active');
    if (a.getAttribute('onclick').indexOf(lang) > -1) {
      a.classList.add('active');
    }
  });
}

document.addEventListener('DOMContentLoaded', function () {
  document.querySelectorAll('nav a').forEach(function (link) {
    link.addEventListener('click', function (e) {
      var target = document.querySelector(this.getAttribute('href'));
      if (target) {
        e.preventDefault();
        target.scrollIntoView({ behavior: 'smooth' });
      }
    });
  });
  setLang('en');
});